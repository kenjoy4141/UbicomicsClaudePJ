for (const s of ALL_SPECS) {
  if (only && s.name !== only) continue;
  const file = path.join(ROOT, "config/variants", `${s.name}.json`);
  fs.writeFileSync(file, JSON.stringify(buildConfig(s), null, 2) + "\n", "utf8");
  console.log(`書き出し: ${file}`);
}
